import compose
import glyphs_cg
from glyphs_latin import G


def codes():
    c = list(range(0x20, 0x7F)) + list(range(0xA0, 0x180))
    c += [0x18F, 0x192, 0x218, 0x219, 0x21A, 0x21B, 0x259]
    c += list(range(0x386, 0x387)) + list(range(0x388, 0x38B)) + [0x38C] + list(range(0x38E, 0x390)) + list(range(0x390, 0x3A2))
    c += list(range(0x3A3, 0x3CF))
    c += list(range(0x400, 0x460))
    c += [0x490, 0x491, 0x492, 0x493, 0x49A, 0x49B, 0x4A2, 0x4A3, 0x4AE, 0x4AF, 0x4B0, 0x4B1, 0x4BA, 0x4BB, 0x4D8, 0x4D9, 0x4E8, 0x4E9]
    c += list(range(0x2010, 0x2016)) + list(range(0x2018, 0x2020)) + [0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2039, 0x203A]
    c += [0x2070] + list(range(0x2074, 0x207A)) + [0x20AC, 0x20BA, 0x20BD, 0x2122]
    c += [0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x221E, 0x2248, 0x2260, 0x2264, 0x2265, 0x2713, 0x2714, 0x2715]
    return sorted(set(c))


def build():
    ent = compose.make_entries(codes())
    return ent


if __name__ == '__main__':
    ent = build()
    miss = [c for c in codes() if c not in ent]
    print(len(ent), 'missing', ''.join(chr(c) for c in miss))
