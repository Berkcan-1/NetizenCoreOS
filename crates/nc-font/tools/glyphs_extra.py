def small(name, src, scale, oy, ox=0):
    ops, adv = G[src]
    x0, y0, x1, y1 = bbox(ops)
    new = scale_ops(ops, scale, scale, ox, oy)
    return new, round(adv * scale)


def build_scaled():
    for code, src in (('\u00b9', '1'), ('\u00b2', '2'), ('\u00b3', '3'), ('\u2070', '0'), ('\u2074', '4'), ('\u2075', '5'),
                      ('\u2076', '6'), ('\u2077', '7'), ('\u2078', '8'), ('\u2079', '9')):
        ops, adv = G[src]
        G[code] = (scale_ops(ops, 0.56, 0.56, 0, 0), round(adv * 0.56) + 20)
    for code, src in (('\u00aa', 'a'), ('\u00ba', 'o')):
        ops, adv = G[src]
        top = scale_ops(ops, 0.62, 0.62, 0, -150)
        x0, _, x1, _ = bbox(top)
        top = top + [(1, x0, 520), (2, x1, 520)]
        G[code] = (top, round(adv * 0.62) + 20)

    nums = {'1': '\u00bc', '2': '\u00bd', '3': '\u00be'}
    for n, code in nums.items():
        d = '4' if code == '\u00bc' else '2' if code == '\u00bd' else '4'
        o1, a1 = G[n]; o2, a2 = G[d]
        top = scale_ops(o1, 0.5, 0.5, 0, -30)
        bot = scale_ops(o2, 0.5, 0.5, 0, 560)
        w1 = round(a1 * 0.5)
        bot = shift(bot, w1 + 110, 0)
        sl = P(); sl.seg(w1 + 40, 1000, w1 + 240, 0)
        ops = top + bot + sl.ops
        G[code] = (ops, w1 + 110 + round(a2 * 0.5) + 10)


def build_all():
    build_marks()
    build_special()
    build_punct()
    build_currency()
    build_arrows()
    build_scaled()


build_all()
