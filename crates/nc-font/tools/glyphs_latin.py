def s_curve(p, cx, y0, y1, rx, a_top=30, a_bot=-150, rx2=None):
    h = (y1 - y0) / 2.0
    ry = h / 2.0
    p.arc(cx, y0 + ry, rx, ry, a_top, 270)
    p.arc(cx, y1 - ry, rx2 or rx, ry, 90, a_bot)
    return p


