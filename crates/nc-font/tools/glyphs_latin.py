G = {}


BEARING = 55


def fin(p, lsb, rsb, name=None):
    lsb += BEARING
    rsb += BEARING
    x0, _, x1, _ = bbox(p.ops)
    ops = shift(p.ops, lsb - x0, 0)
    adv = (x1 - x0) + lsb + rsb
    if name is not None:
        G[name] = (ops, adv)
    return ops, adv


