#[test]
fn lock_roundtrip_and_tamper_detection() {
    use crate::lock::*;
    assert!(secret_is_valid(KIND_PIN, b"0427"));
    assert!(!secret_is_valid(KIND_PIN, b"042"));
    assert!(!secret_is_valid(KIND_PIN, b"04a7"));
    assert!(secret_is_valid(KIND_PASSWORD, b"hunter22"));
    assert!(!secret_is_valid(KIND_PASSWORD, b"short"));

    let record = LockRecord::derive(KIND_PIN, b"0427", [9u8; 16], 50);
    assert!(record.verify(b"0427"));
    assert!(!record.verify(b"0428"));

    let credential = record.to_sector();
    let marker = Marker { enabled: true, fails: 2, credential_digest: LockRecord::sector_digest(&credential) };
    let marker_sector = marker.to_sector();
    match evaluate(&credential, &marker_sector) {
        LockState::Enabled { record: loaded, fails } => {
            assert!(loaded == record);
            assert_eq!(fails, 2);
        }
        _ => panic!("expected enabled"),
    }

    let blank = [0u8; 512];
    assert!(evaluate(&blank, &blank) == LockState::Disabled);
    assert!(evaluate(&blank, &marker_sector) == LockState::Destroyed);
    assert!(evaluate(&credential, &blank) == LockState::Destroyed);

    let mut flipped = credential;
    flipped[40] ^= 1;
    assert!(evaluate(&flipped, &marker_sector) == LockState::Destroyed);
}
