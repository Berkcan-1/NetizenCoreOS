#[test]
fn sha256_streaming_matches_one_shot() {
    let data = [7u8; 300];
    let mut hasher = Sha256::new();
    hasher.update(&data[..13]);
    hasher.update(&data[13..200]);
    hasher.update(&data[200..]);
    assert_eq!(hasher.finalize(), sha256(&data));
}

